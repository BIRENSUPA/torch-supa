class SDistBuild(sdist, object):
    def get_dependencies(self):
        subprocess.run(["git", "submodule", "update", "--init", "--recursive"], check=True, stdout=subprocess.PIPE)

        internal_sudnn_headers = ["sudnn-internal.h", "sudnn-internal_types.h"]

        def copy(src_dir: pathlib.Path, target_dir: pathlib.Path, filename: str):
            if not src_dir.exists():
                print(f"Warning: {src_dir} not found. Please confirm if software stack is installed")
                return

            if not target_dir.exists():
                print(f"Create {target_dir}")
                target_dir.mkdir(parents=True)

            file_path = pathlib.Path(filename)
            src_file_path = src_dir / file_path
            target_file_path = target_dir / file_path

            if not src_file_path.exists():
                print(f"Warning: {src_file_path} not found. Please confirm if software stack is installed.")
                return

            # src_file_path.copy(target_file_path)
            target_file_path.write_text(src_file_path.read_text())

        # copy sudnn internal headers
        source_sudnn_internal_dir = pathlib.Path("/usr/include")
        target_sudnn_internal_dir = pathlib.Path("third-party/biren/sudnn")
        for header in internal_sudnn_headers:
            copy(source_sudnn_internal_dir, target_sudnn_internal_dir, header)

    def run(self) -> None:
        self.get_dependencies()
        super(SDistBuild, self).run()

        third_party_biren_path = pathlib.Path("third-party/biren")
        if third_party_biren_path.exists():
            shutil.rmtree(third_party_biren_path)


def find_dependencies(package_path):
    dependencies = []
    output = subprocess.check_output(["ldd", package_path]).decode("utf-8")
    for line in output.splitlines():
        if "=>" in line:
            dependencies.append(line.split("=>")[0].strip("\t").strip())
    return dependencies


