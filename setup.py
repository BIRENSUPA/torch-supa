def get_cuda_version():
    with open(os.path.join(os.getenv("SUDA_CUDA_HOME"), "include", "cuda.h")) as fi:
        for line in fi:
            m = re.match(r"#define\s+CUDA_VERSION\s+(\d+)", line)
            if m:
                cuda_version = int(m.group(1))
                return f"{cuda_version // 1000}.{cuda_version % 1000 // 10}"
    raise RuntimeError("CUDA_VERSION not found in cuda.h. make sure suda is active.")

