def get_build_version() -> str:
    local_version_label = "br2xx"
    if is_torch_use_isa_enabled():
        local_version_label += ".isa"
    build_mode = get_build_mode()
    version = os.getenv("TORCH_SUPA_VERSION", default="1.0.0")
    torch_versions = [int(v) for v in get_torch_version().split(".")]
    torch_version = torch_versions[0] * 10000 + torch_versions[1] * 100 + torch_versions[2]
    if build_mode != "sdist":
        version += f".{torch_version}"
        full_version_specifiers = r"{}+{}".format(version, local_version_label)
    build_type = get_build_type()
    if (build_type == "Debug" or build_mode == "sdist") and pathlib.Path(".git").exists():
        try:
            full_version_specifiers = version + "+" + "git" + get_torch_supa_git_head_sha(BASE_DIR)
        except:
            pass
    return full_version_specifiers


def update_file_if_change(filepath: str, content: str):
    exist_content = ""
    if os.path.exists(filepath):
        with open(filepath, "r") as fi:
            exist_content = fi.read()
    if exist_content != content:
        with open(filepath, "w") as fo:
            fo.write(content)

