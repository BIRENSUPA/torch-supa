def CppExtension(name, sources, *args, **kwargs):
    r"""
    Creates a :class:`setuptools.Extension` for C++.
    """
    pytorch_dir = get_pytorch_dir()
    temp_include_dirs = kwargs.get("include_dirs", [])
    temp_include_dirs.append(os.path.join(pytorch_dir, "include"))
    kwargs["include_dirs"] = temp_include_dirs

    temp_library_dirs = kwargs.get("library_dirs", [])
    temp_library_dirs.append(os.path.join(pytorch_dir, "lib"))
    kwargs["library_dirs"] = temp_library_dirs

    libraries = kwargs.get("libraries", [])
    libraries.append("c10")
    libraries.append("torch")
    libraries.append("torch_cpu")
    libraries.append("torch_python")
    libraries.append("torch_supa")
    kwargs["libraries"] = libraries
    kwargs["language"] = "c++"
    return Extension(name, sources, *args, **kwargs)


class Clean(distutils.command.clean.clean):

    def run(self):
        f_ignore = open(".gitignore", "r")
        ignores = f_ignore.read()
        pat = re.compile(r"^#( BEGIN NOT-CLEAN-FILES)?")
        clean_flag = True
        filename_list = []
        for wildcard in filter(None, ignores.split("\n")):
            match = pat.match(wildcard)
            if match:
                # Ignore lines which begin with '#'.
                # Ignore files exist only at end of .gitignore
                if match.group(1):
                    clean_flag = False
                    continue
            for filename in glob.glob(wildcard):
                if clean_flag:
                    filename_list.append(filename)
                else:
                    if filename in filename_list:
                        filename_list.remove(filename)
        f_ignore.close()
        for f in filename_list:
            if pathlib.Path(f).is_file():
                os.remove(f)
            else:
                shutil.rmtree(f, ignore_errors=False)

        build_dir = os.path.join(BASE_DIR, f"{TARGET_BUILD_DIR}")
        if pathlib.Path(build_dir).exists():
            shutil.rmtree(build_dir)
        else:
            distutils.command.clean.clean.run(self)

        if CLEAN_TORCH_SUPA_OP:
            SUBMODULE_DIR = os.path.join(BASE_DIR, "third-party/torch-supa-op")
            print(f"Clean torch-supa using its setup.py: {SUBMODULE_DIR}")
            subprocess.check_call(
                ["python3", "setup.py", "clean"],
                cwd=SUBMODULE_DIR
            )



