def get_torch_version():
    try:
        return re.split(r"^([0-9]{1,2}\.[0-9]{1,2}\.[0-9]{1,2}).*", torch.__version__)[1]
    except:
        _, _, exc_traceback = sys.exc_info()
        frame_summary = traceback.extract_tb(exc_traceback)[-1]
        return os.path.dirname(frame_summary.filename)


def get_torch_abi():
    abi_flag = getattr(torch._C, "_PYBIND11_BUILD_ABI", None)
    if abi_flag and abi_flag.startswith("_cxxabi"):
        return abi_flag[-2:]
    # guess abi from compiler of pytorch by existing abi rule.
    # gcc 11 == abi 16
    # gcc 12 == abi 17
    # gcc 13 == abi 18
    # ...
    # generally, new abi format should be compatiable to old.
    m = re.search(r"GCC\s+(\d+)\.\d*", torch.__config__.show())
    if m:
        gcc_major = int(m.group(1))
        return str(gcc_major + 5)
    return "0"


def get_torch_supa_git_head_sha(base_dir) -> str:
    if not pathlib.Path(".git").exists():
        return "N/A"

    torch_supa_git_sha = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=base_dir).decode("ascii").strip()
    return torch_supa_git_sha[:7]


def get_torch_git_head_sha() -> str:
    return torch.version.git_version


