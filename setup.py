def get_src_py_and_dst():
    ret = []
    generated_python_files = glob.glob(os.path.join(BASE_DIR, "torch_supa", "**/*.py"), recursive=True)
    for src in generated_python_files:
        dst = os.path.join(
            os.path.join(BASE_DIR, f"{TARGET_BUILD_DIR}/{get_build_type()}/packages/torch_supa"),
            os.path.relpath(src, os.path.join(BASE_DIR, "torch_supa")),
        )
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        ret.append((src, dst))

    header_files = [
        "torch_supa/csrc/*.h",
        "torch_supa/csrc/*/*.h",
        "torch_supa/csrc/*/*/*.h",
        "torch_supa/csrc/*/*/*/*.h",
        "torch_supa/csrc/aten/operators/*/*.h",
    ]
    glob_header_files = []
    for regex_pattern in header_files:
        glob_header_files += glob.glob(os.path.join(BASE_DIR, regex_pattern), recursive=True)

    for src in glob_header_files:
        dst = os.path.join(
            os.path.join(BASE_DIR, f"{TARGET_BUILD_DIR}/{get_build_type()}/packages/torch_supa/include/torch_supa"),
            os.path.relpath(src, os.path.join(BASE_DIR, "torch_supa")),
        )
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        ret.append((src, dst))

    torch_header_files = ["*/*.h", "*/*/*.h", "*/*/*/*.h", "*/*/*/*/*.h", "*/*/*/*/*/*.h"]
    torch_glob_header_files = []
    for regex_pattern in torch_header_files:
        torch_glob_header_files += glob.glob(os.path.join(BASE_DIR, "patch/include", regex_pattern), recursive=True)

    for src in torch_glob_header_files:
        dst = os.path.join(
            os.path.join(BASE_DIR, f"{TARGET_BUILD_DIR}/{get_build_type()}/packages/torch_supa/include"),
            os.path.relpath(src, os.path.join(BASE_DIR, "patch/include")),
        )
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        ret.append((src, dst))

    generated_json_files = glob.glob(os.path.join(BASE_DIR, "torch_supa", "**/*.json"), recursive=True)
    for src in generated_json_files:
        dst = os.path.join(
            os.path.join(BASE_DIR, f"{TARGET_BUILD_DIR}/{get_build_type()}/packages/torch_supa"),
            os.path.relpath(src, os.path.join(BASE_DIR, "torch_supa")),
        )
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        ret.append((src, dst))

    cmake_file_src = os.path.join(BASE_DIR, "torch_supa", "cmake/TorchSUPAConfig.cmake")
    cmake_file_dst = os.path.join(
        os.path.join(BASE_DIR, f"{TARGET_BUILD_DIR}/{get_build_type()}/packages/torch_supa"),
        os.path.relpath(cmake_file_src, os.path.join(BASE_DIR, "torch_supa")),
    )
    os.makedirs(os.path.dirname(cmake_file_dst), exist_ok=True)
    ret.append((cmake_file_src, cmake_file_dst))
    return ret


